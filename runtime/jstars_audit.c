const char* rt_audit_status(const char* nid_lib, const char* name, const char* origin, const char** note) {
    (void)nid_lib;
    if (origin && !strcmp(origin, "gpu")) {
        *note = "vendored shadPS4 export; classified offline (tools/audit_imports.py), upstream STUBBED functions log at call";
        return "gpu-library";
    }
    for (size_t i = 0; i < sizeof rows / sizeof *rows; ++i)
        if (name && !strcmp(rows[i].name, name)) { *note = rows[i].note; return rows[i].status; }
    *note = "no audit row: add one to runtime/jstars_audit.c";
    return "unclassified";
}
const void* rt_audit_rows(size_t* count) { *count = sizeof rows / sizeof *rows; return rows; }
